'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const input = path.join(root, 'upstream', 'renderer.js');
const output = path.join(root, 'renderer', 'upstream.js');

let source = fs.readFileSync(input, 'utf8');
const exportLine = 'export async function onSettingWindowCreated(view) {';
if (!source.includes(exportLine)) throw new Error('上游 renderer.js 结构变化：未找到 ' + exportLine);
source = source.replace(exportLine, 'async function onSettingWindowCreated(view) {');

const elementsBlock = 'var elements = document\n'
  + '      .querySelector(".chat-msg-area__vlist")\n'
  + '      ?.querySelectorAll(".ml-item");';
if (!source.includes(elementsBlock)) throw new Error('上游 renderer.js 结构变化：未找到消息列表遍历块');
source = source.replace(elementsBlock, elementsBlock + '\n    if (!elements) return;');

// 上游内部的 console.log("[Anti-Recall]", ...) 保留终端可见，同时经宿主桥落盘。
// 只记录参数个数与异常对象，不写消息正文 / msgId 列表。
const ANTI_LOG = String.raw`console.log(...__arArgs); `
  + String.raw`if (window.AntiRecall && window.AntiRecall.log) { `
  + String.raw`const __arError = __arArgs.find(x => x instanceof Error); `
  + String.raw`window.AntiRecall.log(__arError ? "warn" : "debug", `
  + String.raw`"upstream-console", { parts: __arArgs.length, `
  + String.raw`error: __arError ? { message: __arError.message, stack: __arError.stack } : null }); }`;
source = source.replace(
  /console\.log\(("|')\[Anti-Recall\]\1,\s*([\s\S]*?)\);/g,
  (_match, _quote, rest) => {
    const args = '[\"[Anti-Recall]\", ' + rest.trim() + ']';
    return '{ const __arArgs = ' + args + '; ' + ANTI_LOG + ' }';
  }
);

source += '\nwindow.AntiRecall.onSettingWindowCreated = onSettingWindowCreated;\n';

const header = '// GENERATED by tools/build-renderer.cjs from upstream/renderer.js. Do not edit.\n'
  + '// 上游：https://github.com/xh321/LiteLoaderQQNT-Anti-Recall/blob/master/renderer.js\n';
fs.writeFileSync(output, header + source, 'utf8');
console.log('generated', path.relative(root, output), source.length, 'bytes');